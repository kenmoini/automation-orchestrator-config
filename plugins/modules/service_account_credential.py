from ansible_collections.kenmoini.automation_orchestrator_config.plugins.module_utils.orchestrator_api import OrchestratorAPIError, OrchestratorModule, is_uuid


def main():
    argument_spec = dict(
        service_account=dict(type="str", required=True),
        project=dict(type="str"),
        identifier=dict(type="str"),
        grace_period_seconds=dict(type="int"),
        expires_at=dict(type="str"),
        state=dict(type="str", default="present", choices=["present", "absent", "rotated", "enabled", "disabled"]),
    )
    module = OrchestratorModule(argument_spec=argument_spec, supports_check_mode=True)
    module.result_key = "service_account_credential"
    params = module.params
    state = params["state"]
    identifier = params["identifier"]

    if state != "present" and not identifier:
        module.fail_json(msg="identifier is required when state is {0}".format(state))
    if not is_uuid(params["service_account"]) and not params["project"]:
        module.fail_json(msg="project is required when service_account is a name")

    project_id = module.resolve_id("project", params["project"]) if params["project"] else None
    sa_id = module.resolve_id("service_account", params["service_account"], project_id=project_id)
    sa_label = params["service_account"]
    base = "/service_accounts/{0}/credentials".format(sa_id)

    def api(verb, method, path, data=None, expect=None):
        try:
            return module.request(method, path, data=data, expect=expect)
        except OrchestratorAPIError as err:
            module.fail_api(err, "Failed to {0} credential for service account '{1}'".format(verb, sa_label))

    credentials = module.get_all(base, context="Failed to list credential for service account '{0}'".format(sa_label))
    current = None
    if identifier:
        for item in credentials:
            if item.get("identifier") == identifier:
                current = item
                break
        if current is None:
            if state == "absent":
                module.exit_result(False, None)
            module.fail_json(msg="service account credential '{0}' not found".format(identifier))

    if state == "absent":
        module._diff = {"before": current, "after": {}}
        if not module.check_mode:
            try:
                module.request("DELETE", "{0}/{1}".format(base, current["id"]), expect=(200, 202, 204))
            except OrchestratorAPIError as err:
                if err.status != 404:
                    module.fail_api(err, "Failed to delete credential for service account '{0}'".format(sa_label))
                module.exit_result(False, None)
        module.exit_result(True, None)

    if state == "rotated":
        if module.check_mode:
            module.exit_result(True, current)
        body = module.build_desired({"grace_period_seconds": params["grace_period_seconds"]})
        created = api("rotate", "POST", "{0}/{1}/rotate".format(base, current["id"]), data=body)
        secret = created.pop("client_secret", None)
        module.exit_result(True, created, client_id=created.get("identifier"), client_secret=secret)

    if state in ("enabled", "disabled"):
        wanted = "active" if state == "enabled" else "disabled"
        if current.get("status") == wanted:
            module.exit_result(False, current)
        if module.check_mode:
            module.exit_result(True, dict(current, status=wanted))
        action = "enable" if state == "enabled" else "disable"
        updated = api(action, "POST", "{0}/{1}/{2}".format(base, current["id"], action))
        module.exit_result(True, updated if updated is not None else dict(current, status=wanted))

    # state == present
    if current is not None:
        module.exit_result(False, current)
    active = [item for item in credentials if item.get("status") == "active"]
    if active:
        module.exit_result(False, active[0])
    desired = module.build_desired(
        {"credential_type": "client_credentials", "grace_period_seconds": params["grace_period_seconds"], "expires_at": params["expires_at"]}
    )
    if module.check_mode:
        module.exit_result(True, None)
    created = api("create", "POST", base, data=desired)
    secret = created.pop("client_secret", None)
    module.exit_result(True, created, client_id=created.get("identifier"), client_secret=secret)


if __name__ == "__main__":
    main()
